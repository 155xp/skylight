#!/bin/sh
# Regenerate src/nvenc_sys.rs from NVIDIA's nvEncodeAPI.h (Debian/Ubuntu: libffmpeg-nvenc-dev,
# elsewhere nv-codec-headers) with bindgen-cli. Only the structs Skylight passes to the encoder
# are kept; the function table and GUIDs are written by hand in src/nvenc.rs.
set -eu
cd "$(dirname "$0")/.."
hdr=${NVENC_HEADER:-/usr/include/ffnvcodec/nvEncodeAPI.h}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
printf '#include <stdint.h>\n#include "%s"\n' "$hdr" >"$tmp/wrap.h"
bindgen "$tmp/wrap.h" -o "$tmp/out.rs" --no-layout-tests --no-doc-comments --use-core \
  --default-enum-style consts --no-prepend-enum-name \
  --allowlist-type 'NV_ENC_OPEN_ENCODE_SESSION_EX_PARAMS|NV_ENC_INITIALIZE_PARAMS|NV_ENC_PRESET_CONFIG|NV_ENC_RECONFIGURE_PARAMS|NV_ENC_CREATE_INPUT_BUFFER|NV_ENC_CREATE_BITSTREAM_BUFFER|NV_ENC_LOCK_INPUT_BUFFER|NV_ENC_LOCK_BITSTREAM|NV_ENC_PIC_PARAMS|NV_ENC_CAPS_PARAM|NV_ENC_CAPS|NVENCSTATUS|NV_ENC_TUNING_INFO|NV_ENC_PIC_FLAGS|NV_ENC_QP_MAP_MODE|NV_ENC_DEVICE_TYPE' \
  --allowlist-var 'NVENCAPI_.*VERSION|NVENC_INFINITE_GOPLENGTH' \
  --blocklist-item 'NV_ENC_.*_GUID'
# Drop the unused raw bitfield accessors and constructors to keep the file readable.
python3 - "$tmp/out.rs" "$hdr" >src/nvenc_sys.rs <<'PY'
import re, sys
src = open(sys.argv[1]).read()
out, i = [], 0
pat = re.compile(r'(    #\[inline\]\n(    #\[allow\([^)]*\)\]\n)?)?    pub (unsafe )?fn (\w+_raw|new_bitfield_\d+)\(')
while True:
    m = pat.search(src, i)
    if not m:
        out.append(src[i:]); break
    out.append(src[i:m.start()])
    depth, j = 0, src.index('{', m.end())
    while True:
        c = src[j]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    i = j + 2
hdr = open(sys.argv[2]).read()
lic = hdr[hdr.index('/*'):hdr.index('*/') + 2]
print('// Generated by scripts/gen-nvenc-sys.sh from nvEncodeAPI.h, whose license follows.')
print('// Do not edit by hand.\n//')
for line in lic.splitlines():
    print('// ' + line.strip(' /*').rstrip() if line.strip(' /*') else '//')
print('\n#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, unused_imports, clippy::all)]\n')
print(''.join(out))
PY
echo "wrote src/nvenc_sys.rs ($(wc -l <src/nvenc_sys.rs) lines)"
